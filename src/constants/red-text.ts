export const isRedLetterVerse = (book: string, chapter: number, verse: number): boolean => {
  return RED_LETTER_VERSES.some(
    ([b, ch, start, end]) =>
      b.toLowerCase() === book.toLowerCase() &&
      ch === chapter &&
      verse >= start &&
      verse <= end
  );
};